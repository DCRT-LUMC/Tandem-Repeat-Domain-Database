def get_exon_aa_ranges(seq: str):
    exons = []
    aa_index = 1
    seq = [aa for aa in seq if aa.isalpha()]
    if not seq:
        return exons
    current_exon = seq[0]
    current_case = seq[0].isupper()

    for aa in seq[1:]:
        if aa.isupper() == current_case:
            current_exon += aa
        else:
            exons.append((aa_index, aa_index + len(current_exon) - 1))
            aa_index += len(current_exon)
            current_exon = aa
            current_case = aa.isupper()
    if current_exon:
        exons.append((aa_index, aa_index + len(current_exon) - 1))
    return exons

